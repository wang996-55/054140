#!/usr/bin/env node
/**
 * Concatenate src/client/*.js into client.js.
 *
 * The parts are plain fragments of one factory body, so the order matters:
 * header (ids + constants) → core (i18n/api/utils/UI) → stages → shell.
 * No bundler, no dependencies: the shipped file is readable as-is.
 */
import { readFile, writeFile, readdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const sourceDir = path.join(root, 'src', 'client')
const target = path.join(root, 'client.js')

const files = (await readdir(sourceDir)).filter(name => name.endsWith('.js')).sort()
if (files.length === 0) {
  console.error('no client parts found')
  process.exit(1)
}

const parts = []
for (const name of files) {
  const text = await readFile(path.join(sourceDir, name), 'utf8')
  parts.push(`    // ==== ${name} ${'='.repeat(Math.max(4, 64 - name.length))}\n${text.replace(/\s+$/, '')}\n`)
}

const banner = `/* eslint-disable */\n/* Generated by scripts/build-client.mjs from src/client/*.js - do not edit directly. */\n`
const body = banner + parts.join('') 
await writeFile(target, body, 'utf8')
console.log(`client.js written from ${files.length} parts (${Buffer.byteLength(body)} bytes)`)
